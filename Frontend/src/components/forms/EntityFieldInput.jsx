import BilingualInput from '../ui/BilingualInput'
import RefSelect from '../ui/RefSelect'
import { isBilingualField } from '../../utils/entityForm'
import { useEntityBridge } from './EntityBridge'

export default function EntityFieldInput({ field, value, manual, marathiValue, onChange, onMarathiChange, onManualChange }) {
  const common = { id: field.name, name: field.name, className: 'input', placeholder: field.placeholder || '' }
  const bridge = useEntityBridge()

  // Let the other fields of this form find this one (auto-fill, cascading clears, filters).
  if (bridge) bridge.registered.current[field.name] = { value, onChange }

  // Identifiers such as farmer codes and PO numbers are generated by the server on
  // save, so they are shown but never typed.
  if (bridge?.entity?.autoNumberField === field.name) {
    return (
      <input
        id={field.name}
        name={field.name}
        className="input bg-slate-50 text-slate-500"
        value={value || ''}
        placeholder="Generated automatically on save"
        readOnly
        disabled
      />
    )
  }

  if (isBilingualField(field)) {
    return (
      <BilingualInput
        id={field.name}
        label={field.label}
        required={field.required}
        unit={field.unit}
        placeholder={field.placeholder || ''}
        value={value}
        marathiValue={marathiValue}
        manual={manual}
        onChange={onChange}
        onMarathiChange={onMarathiChange}
        onManualChange={onManualChange}
      />
    )
  }

  switch (field.type) {
    case 'boolean':
      return (
        <label className="flex items-center gap-2 py-1.5 text-sm text-slate-700">
          <input type="checkbox" checked={Boolean(value)} onChange={(event) => onChange(event.target.checked)} />
          {field.label}
        </label>
      )
    case 'select':
      return (
        <select {...common} value={value ?? ''} onChange={(event) => onChange(event.target.value)}>
          <option value="">— Select —</option>
          {(field.options || []).map((option) => <option key={option} value={option}>{option}</option>)}
        </select>
      )
    case 'multiselect':
    case 'tags':
      return (
        <select
          {...common}
          multiple
          className="input h-28"
          value={Array.isArray(value) ? value : []}
          onChange={(event) => onChange([...event.target.selectedOptions].map((option) => option.value))}
        >
          {(field.options || []).map((option) => <option key={option} value={option}>{option}</option>)}
        </select>
      )
    case 'ref':
      return (
        <RefSelect
          id={field.name}
          field={field}
          value={value}
          filters={bridge?.filtersFor(field.name) || {}}
          onChange={(next, option) => {
            onChange(next)
            bridge?.applySelection(field.name, next, option)
          }}
        />
      )
    case 'refs':
      return <RefSelect id={field.name} field={field} value={value} multiple onChange={(next) => onChange(next)} />
    case 'date':
      return <input {...common} type="date" value={value || ''} onChange={(event) => onChange(event.target.value)} />
    case 'number':
    case 'decimal':
    case 'currency':
    case 'percent':
      return (
        <input
          {...common}
          type="number"
          step={field.step || (field.type === 'number' ? '1' : '0.01')}
          min={field.min}
          max={field.max}
          value={value ?? ''}
          onChange={(event) => onChange(event.target.value)}
        />
      )
    case 'email':
      return <input {...common} type="email" value={value || ''} onChange={(event) => onChange(event.target.value)} />
    case 'phone':
      return <input {...common} type="tel" value={value || ''} onChange={(event) => onChange(event.target.value)} />
    default:
      return <input {...common} type="text" value={value || ''} onChange={(event) => onChange(event.target.value)} />
  }
}